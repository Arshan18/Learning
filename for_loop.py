# for loop with list 

l = [1, 2, 4, 34, 56, 54]
for i in l:
    print(i)

# for loop with string

s = "Hello Baby"
for i in s:
    print(i)

# for loop with dictionary

d = {"name": "John", "age": "20", "City": "New York"}
for i in d:
    print(i, d[i])

# for loop with tuple 

t = ( 1, 2, 3, 4, 5)
for i in t:
    print(i)